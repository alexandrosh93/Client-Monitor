-- ERP Discovery & Training projects linked to Client Monitor clients.
-- Run once in the same Supabase project as the existing public.clients table.

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS public.client_projects (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  client_id bigint NOT NULL REFERENCES public.clients(id) ON DELETE CASCADE,
  source_project_id text,
  imported_filename text,
  name text NOT NULL DEFAULT 'ERP Implementation' CHECK (char_length(name) BETWEEN 1 AND 150),
  consultant text NOT NULL DEFAULT '',
  phase text NOT NULL DEFAULT 'During Implementation',
  version text NOT NULL DEFAULT '1.0',
  document jsonb NOT NULL DEFAULT '{}'::jsonb,
  schema_version integer NOT NULL DEFAULT 1,
  created_by text NOT NULL DEFAULT '',
  updated_by text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (client_id, source_project_id)
);

CREATE INDEX IF NOT EXISTS client_projects_client_id_idx
  ON public.client_projects(client_id, updated_at DESC);

CREATE TABLE IF NOT EXISTS public.client_project_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id uuid NOT NULL REFERENCES public.client_projects(id) ON DELETE CASCADE,
  action text NOT NULL,
  user_name text NOT NULL DEFAULT '',
  detail jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS client_project_history_project_id_idx
  ON public.client_project_history(project_id, created_at DESC);

ALTER TABLE public.client_projects ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.client_project_history ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS authenticated_client_projects ON public.client_projects;
CREATE POLICY authenticated_client_projects ON public.client_projects
  FOR ALL TO authenticated
  USING (true)
  WITH CHECK (true);

DROP POLICY IF EXISTS authenticated_client_project_history ON public.client_project_history;
CREATE POLICY authenticated_client_project_history ON public.client_project_history
  FOR ALL TO authenticated
  USING (true)
  WITH CHECK (true);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.client_projects TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.client_project_history TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.client_project_history_id_seq TO authenticated;

COMMENT ON TABLE public.client_projects IS 'ERP Discovery, training and readiness projects linked to Client Monitor clients.';
COMMENT ON COLUMN public.client_projects.document IS 'Versioned ERP Discovery document: responses, module items, training stages, roles, requirements and imported history.';

-- Make the new tables available to PostgREST immediately after the migration.
NOTIFY pgrst, 'reload schema';
